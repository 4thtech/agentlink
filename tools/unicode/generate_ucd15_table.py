"""Generates packages/types/src/ucd15.ts: the code points whose UCD 15.0.0 General_Category is one
the D-74 terms character rule refuses (Cc, Cf, Zl, Zp, Co, Cs, Cn; 04 §3.4 "Characters").

Provenance (M1-21; 04 §3.4 "Table provenance"): the spec asks for a table generated from the UCD
15.0.0 file `extracted/DerivedGeneralCategory.txt` with its SHA-256 pinned. That file is not vendored
yet. Until it is, this generator reads General_Category from CPython's `unicodedata` and refuses to
run unless `unicodedata.unidata_version` is exactly "15.0.0" (CPython 3.12 ships UCD 15.0.0; CI's
vectors job runs 3.12). Vendoring the file and switching the input to it is left on the M1-21 card.

Usage: python3.12 -I tools/unicode/generate_ucd15_table.py --write | --check
--check writes nothing and exits 1 if the committed file differs from the output (drift check).
"""

import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "packages" / "types" / "src" / "ucd15.ts"
CATEGORIES = ["Cc", "Cf", "Zl", "Zp", "Co", "Cs", "Cn"]
MISMATCH_EXIT = 1


def ranges():
    out = []
    for cp in range(0x110000):
        cat = unicodedata.category(chr(cp))
        if cat not in CATEGORIES:
            continue
        idx = CATEGORIES.index(cat)
        if out and out[-1][1] == cp - 1 and out[-1][2] == idx:
            out[-1][1] = cp
        else:
            out.append([cp, cp, idx])
    return out


def render():
    rows = ranges()
    lines = [
        "// GENERATED by tools/unicode/generate_ucd15_table.py; do not edit. Drift check:",
        "// `python3.12 -I tools/unicode/generate_ucd15_table.py --check` (run by",
        "// tools/vectors/check-generators.mjs in CI).",
        "//",
        "// The code points whose UCD 15.0.0 General_Category is Cc, Cf, Zl, Zp, Co, Cs or Cn (D-74,",
        "// 04 §3.4 \"Characters\"), as sorted, disjoint ranges [first, last, category index].",
        "// Source: CPython unicodedata, unidata_version 15.0.0 (provenance gap: the spec's pinned",
        "// DerivedGeneralCategory.txt is not vendored yet; see the generator).",
        "",
        "export const UCD15_VERSION = '15.0.0';",
        "export const UCD15_REFUSED_CATEGORIES = Object.freeze([",
    ]
    lines += [f"  '{c}'," for c in CATEGORIES]
    lines += ["] as const);", "", "// prettier-ignore", "export const UCD15_REFUSED_RANGES: readonly number[] = Object.freeze(["]
    for i in range(0, len(rows), 4):
        chunk = rows[i : i + 4]
        lines.append("  " + " ".join(f"0x{a:x}, 0x{b:x}, {c}," for a, b, c in chunk))
    lines += ["]);", ""]
    return "\n".join(lines)


def main(argv):
    if unicodedata.unidata_version != "15.0.0":
        print(
            f"generate_ucd15_table: needs Python's unicodedata at UCD 15.0.0 (CPython 3.12); "
            f"this one is {unicodedata.unidata_version}",
            file=sys.stderr,
        )
        return 2
    text = render()
    if argv[1:] == ["--write"]:
        OUT.write_text(text, encoding="utf-8")
        return 0
    if argv[1:] == ["--check"]:
        if OUT.read_text(encoding="utf-8") != text:
            print(f"generate_ucd15_table: {OUT.relative_to(ROOT)} differs from the generator output", file=sys.stderr)
            return MISMATCH_EXIT
        print("generate_ucd15_table: packages/types/src/ucd15.ts matches UCD 15.0.0")
        return 0
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
