"""Generates packages/types/src/ucd15.ts: the code points whose UCD 15.0.0 General_Category is one
the D-74 terms character rule refuses (Cc, Cf, Zl, Zp, Co, Cs, Cn; 04 §3.4 "Characters").

Provenance (04 §3.4 "Table provenance", M1-21-b): the only input is the vendored UCD 15.0.0 file
tools/unicode/ucd-15.0.0/DerivedGeneralCategory.txt, refused unless its SHA-256 is the one pinned
below (also in tools/unicode/ucd-15.0.0/SHA256SUMS). Nothing is read from the interpreter's own
Unicode database, so any python3 gives the same output.

Usage: python3 -I tools/unicode/generate_ucd15_table.py --write | --check [--table FILE] [--source FILE]
--check writes nothing and exits 1 if the table (default: the committed ucd15.ts) differs from the
output (drift check, run by tools/unicode/check-ucd15.mjs in `pnpm lint`). --source replaces the
input file (tests only); it must still have the pinned SHA-256. Any other failure exits 2.
"""

import argparse
import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "packages" / "types" / "src" / "ucd15.ts"
SOURCE = ROOT / "tools" / "unicode" / "ucd-15.0.0" / "DerivedGeneralCategory.txt"
SOURCE_SHA256 = "fe29a45c0882500e591140aaa5c4f5067e6a5d746806148af34400c48b9c06f9"
HEADER = "# DerivedGeneralCategory-15.0.0.txt"
CATEGORIES = ["Cc", "Cf", "Zl", "Zp", "Co", "Cs", "Cn"]
CODE_SPACE = 0x110000
MISMATCH_EXIT = 1
ERROR_EXIT = 2


class SourceError(Exception):
    pass


def categories(path):
    """The General_Category of every code point, from the pinned file only."""
    data = path.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SOURCE_SHA256:
        raise SourceError(f"{path.name} has SHA-256 {digest}, pinned {SOURCE_SHA256}")
    lines = data.decode("utf-8").split("\n")
    if lines[0] != HEADER:
        raise SourceError(f"{path.name} is not the UCD 15.0.0 file")
    out = [None] * CODE_SPACE
    for line in lines:
        content = line.split("#", 1)[0].strip()
        if not content:
            continue
        span, name = (part.strip() for part in content.split(";"))
        first, _, last = span.partition("..")
        first = int(first, 16)
        last = int(last, 16) if last else first
        for cp in range(first, last + 1):
            if out[cp] is not None:
                raise SourceError(f"U+{cp:04X} is listed twice")
            out[cp] = name
    if None in out:
        raise SourceError(f"U+{out.index(None):04X} has no category")
    return out


def ranges(category):
    out = []
    for cp, cat in enumerate(category):
        if cat not in CATEGORIES:
            continue
        idx = CATEGORIES.index(cat)
        if out and out[-1][1] == cp - 1 and out[-1][2] == idx:
            out[-1][1] = cp
        else:
            out.append([cp, cp, idx])
    return out


def render(category):
    rows = ranges(category)
    lines = [
        "// GENERATED by tools/unicode/generate_ucd15_table.py; do not edit. Drift check:",
        "// `node tools/unicode/check-ucd15.mjs` (part of `pnpm lint`).",
        "//",
        "// The code points whose UCD 15.0.0 General_Category is Cc, Cf, Zl, Zp, Co, Cs or Cn (D-74,",
        "// 04 §3.4 \"Characters\"), as sorted, disjoint ranges [first, last, category index].",
        "// Source: the vendored tools/unicode/ucd-15.0.0/DerivedGeneralCategory.txt, SHA-256",
        f"// {SOURCE_SHA256} (04 §3.4 \"Table provenance\").",
        "// Checked in every runtime by the ucd15-table vectors (table hash, counts and lookups).",
        "",
        "export const UCD15_VERSION = '15.0.0';",
        "export const UCD15_REFUSED_CATEGORIES = Object.freeze([",
    ]
    lines += [f"  '{c}'," for c in CATEGORIES]
    lines += ["] as const);", "", "// prettier-ignore", "export const UCD15_REFUSED_RANGES: readonly number[] = Object.freeze(["]
    for i in range(0, len(rows), 4):
        chunk = rows[i : i + 4]
        lines.append("  " + " ".join(f"0x{a:x}, 0x{b:x}, {c}," for a, b, c in chunk))
    lines += ["]);", ""]
    return "\n".join(lines)


def main(argv):
    parser = argparse.ArgumentParser(description="Generates packages/types/src/ucd15.ts")
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    parser.add_argument("--table", type=Path, default=OUT)
    parser.add_argument("--source", type=Path, default=SOURCE)
    args = parser.parse_args(argv[1:])
    try:
        text = render(categories(args.source))
    except (OSError, ValueError, SourceError) as error:
        print(f"generate_ucd15_table: {error}", file=sys.stderr)
        return ERROR_EXIT
    if args.write:
        args.table.write_text(text, encoding="utf-8")
        return 0
    try:
        committed = args.table.read_text(encoding="utf-8")
    except OSError as error:
        print(f"generate_ucd15_table: {error}", file=sys.stderr)
        return ERROR_EXIT
    if committed != text:
        print(f"generate_ucd15_table: {args.table.name} differs from the generator output", file=sys.stderr)
        return MISMATCH_EXIT
    print(f"generate_ucd15_table: {args.table.name} matches the pinned UCD 15.0.0 file")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
