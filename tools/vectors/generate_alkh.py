# --- test stand-ins for the helpers -----------------------------------------------------------------


def p256_key(label):
    scalar = int.from_bytes(v.det(label, 48), "big") % (P256_N - 1) + 1
    return ec.derive_private_key(scalar, ec.SECP256R1())


def p256_point(key):
    return key.public_key().public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint)


def on_p256(point):
    if len(point) != 65 or point[0] != 0x04:
        return False
    try:
        ec.EllipticCurvePublicKey.from_encoded_point(ec.SECP256R1(), point)
    except ValueError:
        return False
    return True


def se_ecdh(se_key, peer_point):
    """The macOS helper: ECDH(Secure Enclave key, peer) = the 32-byte X coordinate."""
    peer = ec.EllipticCurvePublicKey.from_encoded_point(ec.SECP256R1(), peer_point)
    return se_key.exchange(ec.ECDH(), peer)


class LabelledStream:
    """Deterministic bytes for pycryptodome's randfunc: v.det in counter blocks under one label."""

    def __init__(self, label):
        self.label, self.counter, self.buffer = label, 0, b""

    def __call__(self, n):
        while len(self.buffer) < n:
            self.buffer += v.det(f"{self.label}/{self.counter}", 64)
            self.counter += 1
        out, self.buffer = self.buffer[:n], self.buffer[n:]
        return out


def rsa_key(label, bits=2048):
    return RSA.generate(bits, randfunc=LabelledStream(label))


def ec_spki(key):
    return key.public_key().public_bytes(serialization.Encoding.DER, serialization.PublicFormat.SubjectPublicKeyInfo)


def rsa_spki(key):
    return key.publickey().export_key(format="DER")


def hello_sign(key, challenge):
    """The Windows helper: RSASSA-PKCS1-v1_5 / SHA-256 over the challenge, checked as the helper does."""
    sig = pkcs1_15.new(key).sign(CryptodomeSHA256.new(challenge))
    if pkcs1_15.new(key).sign(CryptodomeSHA256.new(challenge)) != sig:
        v.fail("PKCS#1 v1.5 signing is not deterministic")
    public = serialization.load_der_public_key(rsa_spki(key))
    try:
        public.verify(sig, challenge, rsa_padding.PKCS1v15(), hashes.SHA256())
    except InvalidSignature:
        v.fail("cryptography does not verify the pycryptodome PKCS#1 v1.5 signature")
    return sig


# --- reference implementation of ALKH ---------------------------------------------------------------


def owner_nostr(seed):
    return v.xonly_public_key(hkdf.secp_secret(seed, hkdf.NOSTR, 0))


def info_of(version, kind, cred_id, cred_pub, challenge, owner):
    return INFO_LABEL + v.u8(version) + v.u8(kind) + v.u16be(len(cred_id)) + cred_id + v.sha256(cred_pub) + v.sha256(challenge) + owner


def wrap_key(secret, kind, cred_id, cred_pub, challenge, owner, version=1):
    info = info_of(version, kind, cred_id, cred_pub, challenge, owner)
    key = v.hkdf_sha256(secret, b"", info, 32)
    if key != v.hkdf_sha256_written_out(secret, b"", info, 32):
        v.fail("cryptography HKDF and the written-out RFC 5869 HKDF differ")
    return key


def header(kind, owner, cred_id, cred_pub, challenge, nonce, magic=b"ALKH", version=1, aead=1, cred_len=None, pub_len=None, ch_len=None):
    return (
        magic + v.u8(version) + v.u8(aead) + v.u8(kind) + owner
        + v.u16be(len(cred_id) if cred_len is None else cred_len) + cred_id
        + v.u16be(len(cred_pub) if pub_len is None else pub_len) + cred_pub
        + v.u8(len(challenge) if ch_len is None else ch_len) + challenge
        + nonce
    )


def seal(secret, kind, seed, cred_id, cred_pub, challenge, nonce, owner=None, plaintext=None, key_kind=None, key_version=1, **overrides):
    owner = owner_nostr(seed) if owner is None else owner
    h = header(kind, owner, cred_id, cred_pub, challenge, nonce, **overrides)
    key = wrap_key(secret, kind if key_kind is None else key_kind, cred_id, cred_pub, challenge, owner, key_version)
    return h + v.aes256gcm_encrypt(key, nonce, seed if plaintext is None else plaintext, h)


def parse(blob):
    if len(blob) < 41 or blob[:4] != b"ALKH" or blob[4] != 1 or blob[5] != 1 or blob[6] not in (KIND_MAC, KIND_WIN):
        raise ValueError("not an ALKH v1 header")
    kind, owner, off = blob[6], blob[7:39], 39
    n = int.from_bytes(blob[off : off + 2], "big")
    if n < 1 or n > MAX_CRED_ID or len(blob) < off + 2 + n + 2:
        raise ValueError("bad credIdLen")
    cred_id, off = blob[off + 2 : off + 2 + n], off + 2 + n
    k = int.from_bytes(blob[off : off + 2], "big")
    if (kind == KIND_MAC and k != 65) or (kind == KIND_WIN and not 1 <= k <= MAX_CRED_PUB) or len(blob) < off + 2 + k + 1:
        raise ValueError("bad credPubLen")
    cred_pub, off = blob[off + 2 : off + 2 + k], off + 2 + k
    c = blob[off]
    if c != (65 if kind == KIND_MAC else 32):
        raise ValueError("bad challengeLen")
    challenge, off = blob[off + 1 : off + 1 + c], off + 1 + c
    if len(blob) != 104 + n + k + c:
        raise ValueError("bad size")
    if not credential_fits(kind, cred_id, cred_pub, challenge):
        raise ValueError("credential does not fit the kind")
    return {"kind": kind, "owner": owner, "credId": cred_id, "credPub": cred_pub, "challenge": challenge, "headerLength": off + 12}


def is_name(cred_id):
    return 1 <= len(cred_id) <= MAX_NAME and all(0x21 <= b <= 0x7E for b in cred_id)


def rsa_modulus_bytes(spki):
    """The byte length of an RSA SubjectPublicKeyInfo's modulus (256, 384 or 512), else None."""
    try:
        key = serialization.load_der_public_key(spki)
    except (ValueError, TypeError):
        return None
    if not isinstance(key, rsa.RSAPublicKey):
        return None
    if key.public_bytes(serialization.Encoding.DER, serialization.PublicFormat.SubjectPublicKeyInfo) != spki:
        return None
    n = (key.key_size + 7) // 8
    return n if n in (256, 384, 512) else None


def credential_fits(kind, cred_id, cred_pub, challenge):
    if not 1 <= len(cred_id) <= MAX_CRED_ID:
        return False
    if kind == KIND_MAC:
        # Fable review of DESK-D12a (low 1): a peer with the X coordinate of G or of the credential
        # key is refused, so -G and -credPub are refused as well as G and credPub.
        return on_p256(cred_pub) and on_p256(challenge) and challenge[1:33] not in (P256_G[1:33], cred_pub[1:33])
    return (
        is_name(cred_id)
        and 1 <= len(cred_pub) <= MAX_CRED_PUB
        and rsa_modulus_bytes(cred_pub) is not None
        and len(challenge) == 32
    )


# The helper records of DESK-D12b (apps/desktop/native/*/agentlink-presence.*, record v1), rebuilt
# from and read into the ALKH header fields (04 §2.3.4 "Helper record").
def helper_record(kind, cred_id, cred_pub, challenge):
    if kind == KIND_MAC:
        return v.u8(1) + v.u16be(len(cred_id)) + cred_id + cred_pub + challenge
    return v.u8(1) + v.u8(len(cred_id)) + cred_id + v.u16be(len(cred_pub)) + cred_pub + challenge


def read_helper_record(kind, rec):
    if kind not in (KIND_MAC, KIND_WIN) or len(rec) < 4 or rec[0] != 1:
        raise ValueError("not a helper record v1")
    if kind == KIND_MAC:
        n = int.from_bytes(rec[1:3], "big")
        if len(rec) != 3 + n + 130:
            raise ValueError("bad record size")
        fields = rec[3 : 3 + n], rec[3 + n : 68 + n], rec[68 + n :]
    else:
        n = rec[1]
        if len(rec) < 2 + n + 2:
            raise ValueError("bad record size")
        k = int.from_bytes(rec[2 + n : 4 + n], "big")
        if len(rec) != 4 + n + k + 32:
            raise ValueError("bad record size")
        fields = rec[2 : 2 + n], rec[4 + n : 4 + n + k], rec[4 + n + k :]
    if not credential_fits(kind, *fields):
        raise ValueError("record does not fit the kind")
    return fields


def secret_fits(kind, secret, cred_pub=None):
    if kind == KIND_MAC and len(secret) != 32:
        return False
    # Fable review of DESK-D12a (low 3): the signature is exactly as long as the SPKI modulus.
    if kind == KIND_WIN and (len(secret) not in (256, 384, 512) or len(secret) != rsa_modulus_bytes(cred_pub)):
        return False
    return any(secret)


def open_alkh(blob, secret, expected_owner=None, expected_kind=None):
    h = parse(blob)
    if not secret_fits(h["kind"], secret, h["credPub"]):
        raise ValueError("native secret does not fit the kind")
    if expected_owner is not None and h["owner"] != expected_owner:
        raise ValueError("header owner is not the expected owner")
    if expected_kind is not None and h["kind"] != expected_kind:
        raise ValueError("kind is not this platform's")
    hl = h["headerLength"]
    key = wrap_key(secret, h["kind"], h["credId"], h["credPub"], h["challenge"], h["owner"])
    seed = v.aes256gcm_decrypt(key, blob[hl - 12 : hl], blob[hl:], blob[:hl])
    if len(seed) != 32 or owner_nostr(seed) != h["owner"]:
        raise ValueError("seed does not derive the header owner")
    return seed


def refused(fn, *args):
    try:
        fn(*args)
    except Exception:
        return True
    return False


def flipped(data, offset):
    out = bytearray(data)
    out[offset] ^= 0x01
    return bytes(out)


# --- cases ------------------------------------------------------------------------------------------


def build():
    cases = []
    seed, other_seed = v.det("alkh/seed/1", 32), v.det("alkh/seed/2", 32)
    owner, other = owner_nostr(seed), owner_nostr(other_seed)

    # Test stand-ins: the Secure Enclave key and its per-install peer keys (their secrets are dropped
    # here, as the helper's `create` discards the peer secret); the Hello credential and its challenges.
    se_key, se_key2 = p256_key("alkh/se-key/1"), p256_key("alkh/se-key/2")
    se_pub, se_pub2 = p256_point(se_key), p256_point(se_key2)
    peer, peer2 = p256_point(p256_key("alkh/peer/1")), p256_point(p256_key("alkh/peer/2"))
    mac_secret = se_ecdh(se_key, peer)
    if mac_secret != p256_key("alkh/peer/1").exchange(ec.ECDH(), se_key.public_key()):
        v.fail("ECDH is not symmetric")
    if se_ecdh(se_key, peer2) == mac_secret or se_ecdh(se_key2, peer) == mac_secret:
        v.fail("two peers or two keys give the same ECDH secret")
    # ECDH with the base point would give the public key's X coordinate: never a secret.
    if se_ecdh(se_key, P256_G) != se_pub[1:33]:
        v.fail("ECDH with G is not the public X coordinate")

    rsa1, rsa2 = rsa_key("alkh/hello-key/1"), rsa_key("alkh/hello-key/2")
    rsa3072, rsa4096 = rsa_key("alkh/hello-key/3072", 3072), rsa_key("alkh/hello-key/4096", 4096)
    win_pub, win_pub2 = rsa_spki(rsa1), rsa_spki(rsa2)
    challenge, challenge2 = v.det("alkh/hello-challenge/1", 32), v.det("alkh/hello-challenge/2", 32)
    win_secret = hello_sign(rsa1, challenge)
    win_secret_other_challenge = hello_sign(rsa1, challenge2)
    win_secret_other_key = hello_sign(rsa2, challenge)
    if len(win_secret) != 256 or len(win_pub) > MAX_CRED_PUB:
        v.fail("unexpected RSA-2048 sizes")

    mac_cred = v.det("alkh/se-handle/569", 569)  # a Secure Enclave dataRepresentation stand-in
    win_cred = ("AgentLink-owner-" + v.det("alkh/hello-name", 16).hex()).encode("ascii")  # a KeyCredential name

    def wrap_case(case_id, why, secret, kind, cred, pub, ch, own):
        return v.case(
            case_id,
            f"{SPEC} key: wrapKey = HKDF-SHA256(ikm = nativeSecret, salt = \"\", info = \"agentlink/v1/owner-native-wrap\" | version | kind | u16be credIdLen | credId | SHA-256(credPub) | SHA-256(challenge) | ownerNostr, 32); {why}",
            {"op": "wrapKey", "kind": kind, "nativeSecret": v.hx(secret), "credentialId": v.hx(cred), "credentialPublicKey": v.hx(pub), "challenge": v.hx(ch), "ownerNostr": v.hx(own)},
            {"wrapKey": v.hx(wrap_key(secret, kind, cred, pub, ch, own))},
        )

    cases.append(wrap_case("wrap-key-mac", "kind 1, the ECDH secret of a test Secure Enclave key and a per-install peer key", mac_secret, KIND_MAC, mac_cred, se_pub, peer, owner))
    cases.append(wrap_case("wrap-key-win", "kind 2, the PKCS#1 v1.5 / SHA-256 signature of a test RSA-2048 Hello key over a per-install challenge", win_secret, KIND_WIN, win_cred, win_pub, challenge, owner))
    keys = {
        wrap_key(mac_secret, KIND_MAC, mac_cred, se_pub, peer, owner),
        wrap_key(mac_secret, KIND_MAC, mac_cred, se_pub, peer, other),
        wrap_key(mac_secret, KIND_MAC, mac_cred, se_pub2, peer, owner),
        wrap_key(mac_secret, KIND_MAC, mac_cred, se_pub, peer2, owner),
        wrap_key(mac_secret, KIND_MAC, mac_cred[:-1], se_pub, peer, owner),
        wrap_key(mac_secret, KIND_MAC, mac_cred, se_pub, peer, owner, version=2),
    }
    if len(keys) != 6:
        v.fail("the info does not bind owner, credential public key, challenge, credential ID and version")
    cases.append(wrap_case("wrap-key-mac-other-owner", "kind 1 for another owner public key (a different wrapKey)", mac_secret, KIND_MAC, mac_cred, se_pub, peer, other))

    def open_in(blob, secret, expected_owner=None, expected_kind=None):
        return {"op": "openNative", "blob": v.hx(blob), "nativeSecret": v.hx(secret), "expectedOwnerNostr": "" if expected_owner is None else v.hx(expected_owner), "expectedKind": 0 if expected_kind is None else expected_kind}

    def seal_in(secret, kind, cred, pub, ch, nonce):
        return {"op": "sealNative", "kind": kind, "nativeSecret": v.hx(secret), "seed": v.hx(seed), "credentialId": v.hx(cred), "credentialPublicKey": v.hx(pub), "challenge": v.hx(ch), "nonce": v.hx(nonce)}

    blobs = {}
    for case_id, why, kind, secret, cred, pub, ch in [
        ("mac-569", "kind 1 with a 569-byte Secure Enclave handle", KIND_MAC, mac_secret, mac_cred, se_pub, peer),
        ("mac-1", "kind 1 with the shortest credential ID (1 byte)", KIND_MAC, mac_secret, v.det("alkh/cred/1", 1), se_pub, peer),
        ("mac-1024", "kind 1 with the longest credential ID (1024 bytes)", KIND_MAC, mac_secret, v.det("alkh/cred/1024", 1024), se_pub, peer),
        ("win-name", "kind 2 with a KeyCredential name and an RSA-2048 SubjectPublicKeyInfo", KIND_WIN, win_secret, win_cred, win_pub, challenge),
        ("win-3072", "kind 2 with an RSA-3072 SubjectPublicKeyInfo and its 384-byte signature", KIND_WIN, hello_sign(rsa3072, challenge), win_cred, rsa_spki(rsa3072), challenge),
        ("win-4096", "kind 2 with an RSA-4096 SubjectPublicKeyInfo and its 512-byte signature", KIND_WIN, hello_sign(rsa4096, challenge), win_cred, rsa_spki(rsa4096), challenge),
    ]:
        nonce = v.det(f"alkh/{case_id}/nonce", 12)
        blob = seal(secret, kind, seed, cred, pub, ch, nonce)
        if len(blob) != 104 + len(cred) + len(pub) + len(ch) or open_alkh(blob, secret, owner, kind) != seed:
            v.fail(f"{case_id}: the reference ALKH opener disagrees")
        blobs[case_id] = (blob, secret, cred, pub, ch, nonce, kind)
        cases.append(v.case(f"seal-{case_id}", f"{SPEC} seal ({why}); ownerNostr is derived from the seed", seal_in(secret, kind, cred, pub, ch, nonce), {"blob": v.hx(blob)}))
        cases.append(v.case(f"open-{case_id}", f"{SPEC} open ({why}) with the expected owner and kind", open_in(blob, secret, owner, kind), {"seed": v.hx(seed)}))
        cases.append(v.case(f"header-{case_id}", f"{SPEC} header fields ({why}), read before the helper runs", {"op": "nativeHeader", "blob": v.hx(blob)}, {"kind": str(kind), "ownerNostr": v.hx(owner), "credentialId": v.hx(cred), "credentialPublicKey": v.hx(pub), "challenge": v.hx(ch)}))

    m, msecret, mcred, mpub, mch, mnonce, _ = blobs["mac-569"]
    w, wsecret, wcred, wpub, wch, wnonce, _ = blobs["win-name"]
    cases.append(v.case("open-mac-no-expected", f"{SPEC} open with no expected owner or kind; the seed still derives the header owner", open_in(m, msecret), {"seed": v.hx(seed)}))
    cases.append(v.case("open-win-repeat-gesture", f"{SPEC} open with a second, independently made PKCS#1 v1.5 signature over the same challenge (deterministic, so the same bytes)", open_in(w, hello_sign(rsa1, wch), owner, KIND_WIN), {"seed": v.hx(seed)}))

    def reject(case_id, why, blob, secret, expected_owner=None, expected_kind=None):
        if not refused(open_alkh, blob, secret, expected_owner, expected_kind):
            v.fail(f"{case_id}: the reference ALKH opener accepts it")
        cases.append(v.case(f"open-reject-{case_id}", f"{SPEC}: {why}", open_in(blob, secret, expected_owner, expected_kind), {"outcome": "reject"}))

    def mac_seal(**kw):
        args = {"secret": msecret, "kind": KIND_MAC, "seed": seed, "cred_id": mcred, "cred_pub": mpub, "challenge": mch, "nonce": mnonce}
        args.update(kw)
        return seal(**args)

    def win_seal(**kw):
        args = {"secret": wsecret, "kind": KIND_WIN, "seed": seed, "cred_id": wcred, "cred_pub": wpub, "challenge": wch, "nonce": wnonce}
        args.update(kw)
        return seal(**args)

    # Wrong key: another secret, the binding (another credential, challenge or owner in the info).
    reject("mac-wrong-secret", "kind 1: the ECDH secret of another Secure Enclave key", m, se_ecdh(se_key2, peer))
    reject("mac-other-peer-secret", "kind 1: the ECDH secret for another install's peer key", m, se_ecdh(se_key, peer2))
    reject("win-other-key", "kind 2: the signature of another Hello credential over the same challenge", w, win_secret_other_key)
    reject("win-other-challenge", "kind 2: the signature over another install's challenge", w, win_secret_other_challenge)
    reject("bind-cred-pub", "binding: the key derived with another credential public key in the info, under the same secret", seal_with_info(msecret, KIND_MAC, seed, mcred, mpub, mch, mnonce, {"cred_pub": se_pub2}), msecret)
    reject("bind-cred-id", "binding: the key derived with another credential ID in the info, under the same secret", seal_with_info(msecret, KIND_MAC, seed, mcred, mpub, mch, mnonce, {"cred_id": mcred[:-1]}), msecret)
    reject("bind-challenge-info", "binding: the key derived with another per-install challenge in the info, under the same secret", seal_with_info(msecret, KIND_MAC, seed, mcred, mpub, mch, mnonce, {"challenge": peer2}), msecret)
    reject("bind-challenge-swapped", "binding: the challenge in the header rewritten to another peer key (AAD and info)", m[: 39 + 2 + len(mcred) + 2 + 65 + 1] + peer2 + m[39 + 2 + len(mcred) + 2 + 65 + 1 + 65 :], msecret)
    reject("bind-owner-info", "binding: the seed sealed under the info of another owner public key, header naming the right owner", seal_with_info(msecret, KIND_MAC, seed, mcred, mpub, mch, mnonce, {"owner": other}), msecret)
    reject("bind-kind-info", "binding: a kind 1 header whose key was derived with kind 2 in the info", mac_seal(key_kind=KIND_WIN), msecret)
    reject("bind-version-info", "binding: a version 1 header whose key was derived with version 2 in the info", mac_seal(key_version=2), msecret)
    # Secret length and value (before decryption).
    reject("mac-secret-31", "kind 1: a 31-byte secret, refused before decryption", m, msecret[:31])
    reject("mac-secret-33", "kind 1: a 33-byte secret, refused before decryption", m, msecret + b"\x00")
    reject("mac-secret-zero", "kind 1: an all-zero secret, refused before decryption", m, bytes(32))
    reject("win-secret-255", "kind 2: a 255-byte signature, refused before decryption", w, wsecret[:255])
    reject("win-secret-32", "kind 2: a 32-byte secret, refused before decryption", w, wsecret[:32])
    reject("win-secret-zero", "kind 2: an all-zero 256-byte secret, refused before decryption", w, bytes(256))
    # Expected owner and kind.
    reject("other-owner", "the header owner is not the expected owner, refused before decryption", m, msecret, other)
    reject("other-kind", "a kind 1 blob where the platform expects kind 2, refused before decryption", m, msecret, owner, KIND_WIN)
    reject("seed-not-owner", "the seed does not derive the header owner (sealed validly with another owner key)", mac_seal(owner=other), msecret)
    reject("seed-31", "a 31-byte plaintext (sealed validly), refused by size", mac_seal(plaintext=seed[:31]), msecret)
    # Version, aead, kind.
    reject("version-2", "version 2 (sealed validly)", mac_seal(version=2), msecret)
    reject("version-0", "version 0 (sealed validly)", mac_seal(version=0), msecret)
    reject("aead-2", "aead 2 (sealed validly)", mac_seal(aead=2), msecret)
    reject("kind-0", "kind 0 (sealed validly)", seal(msecret, 0, seed, mcred, mpub, mch, mnonce), msecret)
    reject("kind-3", "kind 3 (sealed validly)", seal(msecret, 3, seed, mcred, mpub, mch, mnonce), msecret)
    reject("mac-as-kind-2", "a kind 1 layout with the kind byte set to 2 (sealed validly; a 65-byte challenge does not fit kind 2)", seal(msecret, KIND_WIN, seed, mcred, mpub, mch, mnonce), msecret)
    # Lengths.
    reject("truncated", "one byte short", m[:-1], msecret)
    reject("extended", "one byte too many", m + b"\x00", msecret)
    reject("header-only", "truncated to the header", m[: 104 - 48 + len(mcred) + 65 + 65], msecret)
    reject("short", "shorter than the smallest header", m[:30], msecret)
    reject("empty", "empty", b"", msecret)
    reject("cred-len-0", "credIdLen 0 (sealed validly)", mac_seal(cred_id=b""), msecret)
    reject("cred-len-1025", "credIdLen 1025 (sealed validly)", mac_seal(cred_id=v.det("alkh/cred/1025", 1025)), msecret)
    reject("cred-len-mismatch", "credIdLen one more than the bytes present", m[:39] + v.u16be(len(mcred) + 1) + m[41:], msecret)
    reject("mac-pub-64", "kind 1: a 64-byte credPub (sealed validly)", mac_seal(cred_pub=mpub[:64]), msecret)
    reject("mac-challenge-33", "kind 1: a 33-byte compressed peer point (sealed validly)", mac_seal(challenge=bytes([2 + (mch[64] & 1)]) + mch[1:33]), msecret)
    reject("win-pub-0", "kind 2: credPubLen 0 (sealed validly)", win_seal(cred_pub=b""), wsecret)
    reject("win-pub-2049", "kind 2: credPubLen 2049 (sealed validly)", win_seal(cred_pub=v.det("alkh/win-pub/2049", 2049)), wsecret)
    reject("win-name-65", "kind 2: a 65-byte credential name (sealed validly)", win_seal(cred_id=b"A" * 65), wsecret)
    reject("win-name-not-ascii", "kind 2: a credential name with a byte outside printable ASCII (sealed validly)", win_seal(cred_id=wcred[:-1] + b"\x00"), wsecret)
    reject("win-challenge-31", "kind 2: a 31-byte challenge (sealed validly)", win_seal(challenge=wch[:31]), wsecret)
    reject("win-challenge-33", "kind 2: a 33-byte challenge (sealed validly)", win_seal(challenge=wch + b"\x00"), wsecret)
    # Points.
    off_curve = mch[:64] + bytes([mch[64] ^ 0x01])
    if on_p256(off_curve):
        v.fail("the off-curve test point is on the curve")
    reject("mac-challenge-off-curve", "kind 1: a peer point that is not on P-256 (sealed validly)", mac_seal(challenge=off_curve), msecret)
    off_pub = mpub[:64] + bytes([mpub[64] ^ 0x01])
    if on_p256(off_pub):
        v.fail("the off-curve test public key is on the curve")
    reject("mac-pub-off-curve", "kind 1: a credential public key that is not on P-256 (sealed validly)", mac_seal(cred_pub=off_pub), msecret)
    reject("mac-pub-prefix-06", "kind 1: a credential public key with the hybrid prefix 06 (sealed validly)", mac_seal(cred_pub=b"\x06" + mpub[1:]), msecret)
    g_secret = se_ecdh(se_key, P256_G)
    reject("mac-challenge-g", "kind 1: the base point G as the peer key, whose ECDH secret is public (sealed validly)", mac_seal(challenge=P256_G, secret=g_secret), g_secret)
    neg_g = P256_G[:33] + (P256_P - int.from_bytes(P256_G[33:], "big")).to_bytes(32, "big")
    if not on_p256(neg_g) or neg_g == P256_G:
        v.fail("-G is not a point other than G")
    neg_g_secret = se_ecdh(se_key, neg_g)
    reject("mac-challenge-neg-g", "kind 1: -G as the peer key (the X coordinate of G; its ECDH secret is the public X coordinate too) (sealed validly)", mac_seal(challenge=neg_g, secret=neg_g_secret), neg_g_secret)
    neg_pub = mpub[:33] + (P256_P - int.from_bytes(mpub[33:], "big")).to_bytes(32, "big")
    if not on_p256(neg_pub):
        v.fail("-credPub is not on the curve")
    reject("mac-challenge-neg-pub", "kind 1: -credPub as the peer key (the X coordinate of the credential key) (sealed validly)", mac_seal(challenge=neg_pub, secret=se_ecdh(se_key, neg_pub)), se_ecdh(se_key, neg_pub))
    w3 = blobs["win-3072"]
    reject("win-secret-384-for-2048", "kind 2: a 384-byte signature for an RSA-2048 credential (the length is tied to the SPKI modulus), refused before decryption", w, hello_sign(rsa3072, wch))
    reject("win-secret-256-for-3072", "kind 2: a 256-byte signature for an RSA-3072 credential, refused before decryption", w3[0], wsecret)
    reject("win-pub-not-rsa", "kind 2: a credential public key that is not an RSA SubjectPublicKeyInfo (a P-256 SPKI; sealed validly)", win_seal(cred_pub=ec_spki(se_key)), wsecret)
    reject("mac-challenge-is-pub", "kind 1: the credential public key as the peer key (sealed validly)", mac_seal(challenge=mpub, secret=se_ecdh(se_key, mpub)), se_ecdh(se_key, mpub))
    # Bit flips in every field.
    hl = 39 + 2 + len(mcred) + 2 + 65 + 1 + 65 + 12
    for field, offset in [("magic", 0), ("version", 4), ("aead", 5), ("kind", 6), ("owner", 7), ("cred-len", 40), ("cred-id", 41), ("cred-pub-len", 42 + len(mcred)), ("cred-pub", 41 + len(mcred) + 2 + 40), ("challenge-len", 41 + len(mcred) + 2 + 65), ("challenge", 41 + len(mcred) + 2 + 65 + 1 + 40), ("nonce", hl - 1), ("ciphertext", hl), ("tag", len(m) - 1)]:
        reject(f"flip-{field}", f"one bit flipped ({field})", flipped(m, offset), msecret)
    for field, offset in [("challenge", len(w) - 48 - 12 - 1), ("cred-pub", 39 + 2 + len(wcred) + 2 + 100), ("tag", len(w) - 1)]:
        reject(f"win-flip-{field}", f"kind 2: one bit flipped ({field})", flipped(w, offset), wsecret)

    cases.append(v.case("header-reject-version-2", f"{SPEC}: the header reader refuses version 2", {"op": "nativeHeader", "blob": v.hx(mac_seal(version=2))}, {"outcome": "reject"}))
    cases.append(v.case("header-reject-truncated", f"{SPEC}: the header reader refuses a blob one byte short", {"op": "nativeHeader", "blob": v.hx(m[:-1])}, {"outcome": "reject"}))
    cases.append(v.case("header-reject-off-curve", f"{SPEC}: the header reader refuses an off-curve peer point", {"op": "nativeHeader", "blob": v.hx(mac_seal(challenge=off_curve))}, {"outcome": "reject"}))

    # Helper records (DESK-D12b record v1) ---------------------------------------------------------
    def record_case(case_id, why, kind, cred, pub, ch):
        rec = helper_record(kind, cred, pub, ch)
        if read_helper_record(kind, rec) != (cred, pub, ch):
            v.fail(f"{case_id}: the reference record reader disagrees")
        cases.append(v.case(f"record-{case_id}", f"{SPEC} helper record ({why}), rebuilt from the header fields", {"op": "helperRecord", "kind": kind, "credentialId": v.hx(cred), "credentialPublicKey": v.hx(pub), "challenge": v.hx(ch)}, {"record": v.hx(rec)}))
        cases.append(v.case(f"read-record-{case_id}", f"{SPEC} helper record ({why}) read into the header fields", {"op": "readHelperRecord", "kind": kind, "record": v.hx(rec)}, {"credentialId": v.hx(cred), "credentialPublicKey": v.hx(pub), "challenge": v.hx(ch)}))
        return rec

    mrec = record_case("mac", "kind 1: 01 | u16be L | SE key handle | SE public key | peer public key", KIND_MAC, mcred, mpub, mch)
    wrec = record_case("win", "kind 2: 01 | u8 N | credential name | u16be S | SPKI | challenge", KIND_WIN, wcred, wpub, wch)

    def record_reject(case_id, why, kind, rec):
        if not refused(read_helper_record, kind, rec):
            v.fail(f"{case_id}: the reference record reader accepts it")
        cases.append(v.case(f"read-record-reject-{case_id}", f"{SPEC} helper record: {why}", {"op": "readHelperRecord", "kind": kind, "record": v.hx(rec)}, {"outcome": "reject"}))

    record_reject("mac-version-2", "record version 2", KIND_MAC, b"\x02" + mrec[1:])
    record_reject("mac-truncated", "one byte short", KIND_MAC, mrec[:-1])
    record_reject("mac-extended", "one byte too many", KIND_MAC, mrec + b"\x00")
    record_reject("mac-peer-off-curve", "a peer point that is not on P-256", KIND_MAC, mrec[:-1] + bytes([mrec[-1] ^ 1]))
    record_reject("mac-peer-g", "the base point G as the peer point", KIND_MAC, helper_record(KIND_MAC, mcred, mpub, P256_G))
    record_reject("mac-as-win", "a kind 1 record read as kind 2", KIND_WIN, mrec)
    record_reject("win-truncated", "one byte short", KIND_WIN, wrec[:-1])
    record_reject("win-name-0", "an empty credential name", KIND_WIN, helper_record(KIND_WIN, b"", wpub, wch))
    record_reject("win-as-mac", "a kind 2 record read as kind 1", KIND_MAC, wrec)
    record_reject("empty", "empty", KIND_MAC, b"")

    # Cross-type ----------------------------------------------------------------------------------
    prf_out = v.det("alkh/prf-output", 32)
    alkp = prf.seal_alkp(prf_out, seed, v.det("alkh/alkp-cred", 16), v.det("alkh/alkp-nonce", 12))
    if prf.open_alkp(alkp, prf_out, owner) != seed:
        v.fail("the ALKP reference opener disagrees")
    reject("alkp-blob", "an ALKP blob given to the ALKH reader (its PRF output as the secret)", alkp, prf_out)
    reject("alkp-magic-patched", "an ALKP blob with its magic rewritten to ALKH", b"ALKH" + alkp[4:], prf_out)
    reject("alkh-label-as-alkp", "ALKH magic on a blob sealed in the ALKP layout and key", prf.seal_alkp(prf_out, seed, v.det("alkh/alkp-cred", 16), v.det("alkh/alkp-nonce", 12), magic=b"ALKH"), prf_out)
    code = v.det("alkh/owner-code", 15)
    code_text = base64.b32encode(code).decode("ascii")
    alko_salt, alko_nonce = v.det("alkh/alko/salt", 16), v.det("alkh/alko/nonce", 12)
    alko_header = ksf.header(1, *FLOOR, alko_salt, alko_nonce, "", magic=b"ALKO")
    alko = alko_header + v.aes256gcm_encrypt(ksf.kek(code_text, 1, alko_salt, *FLOOR, ksf.ALKO_INFO), alko_nonce, seed, alko_header)
    if ksf.open_alko(alko, code_text, ksf.owner_keys(seed), True) != seed:
        v.fail("the ALKO reference opener disagrees")
    reject("alko-blob", "an ALKO blob given to the ALKH reader", alko, msecret)
    # Fable review of DESK-D12a (low 4): the other blob types given to the ALKH reader.
    alkr = prf.seal_alkr(code_text, seed, v.det("alkh/alkr/salt", 16), v.det("alkh/alkr/nonce", 12), FLOOR)
    reject("alkr-blob", "an ALKR (recovery code) blob given to the ALKH reader", alkr, msecret)
    alks = ksf.seal(code_text, 2, *FLOOR, v.det("alkh/alks/salt", 16), v.det("alkh/alks/nonce", 12), "0x" + "11" * 20, seed)
    reject("alks-blob", "an ALKS (agent keystore file) blob given to the ALKH reader", alks, msecret)
    alkk = rk.header(v.det("alkh/alkk/salt", 16), 1 << 16, v.det("alkh/alkk/prefix", 8), owner, *FLOOR) + v.det("alkh/alkk/body", 64)
    reject("alkk-blob", "an ALKK (recovery kit) header and body given to the ALKH reader", alkk, msecret)
    alf1 = st.seal(v.det("alkh/alf1/key", 32), v.det("alkh/alf1/prefix", 8), 1 << 16, seed)
    reject("alf1-blob", "an ALF1 (encrypted file) object given to the ALKH reader", alf1, msecret)
    for name, blob in [("alkr", alkr), ("alks", alks), ("alkk", alkk), ("alf1", alf1)]:
        cases.append(v.case(f"header-reject-{name}", f"{SPEC}: the header reader refuses an {name.upper()} blob", {"op": "nativeHeader", "blob": v.hx(blob)}, {"outcome": "reject"}))

    def cross(case_id, why, reader, blob, secret):
        cases.append(v.case(f"cross-{case_id}", f"{SPEC} type separation: {why}", {"op": "crossOpen", "reader": reader, "blob": v.hx(blob), "secret": secret}, {"outcome": "reject"}))

    if not refused(prf.open_alkp, m, msecret) or not refused(prf.open_alkp, b"ALKP" + m[4:], msecret):
        v.fail("the ALKP reference opener accepts an ALKH blob")
    cross("alkh-to-passkey", "an ALKH blob given to the ALKP reader (its native secret as the PRF output)", "passkey", m, v.hx(msecret))
    cross("alkh-magic-to-passkey", "an ALKH blob with its magic rewritten to ALKP, given to the ALKP reader", "passkey", b"ALKP" + m[4:], v.hx(msecret))
    if not refused(prf.open_alkr, m, code_text):
        v.fail("the ALKR reference opener accepts an ALKH blob")
    cross("alkh-to-recovery", "an ALKH blob given to the ALKR reader", "recovery", m, code_text)
    if not refused(ksf.open_alko, m, code_text, ksf.owner_keys(seed), True):
        v.fail("the ALKO reference opener accepts an ALKH blob")
    cross("alkh-to-owner", "an ALKH blob given to the ALKO reader", "owner", m, code_text)
    return cases


def seal_with_info(secret, kind, seed, cred_id, cred_pub, challenge, nonce, info):
    """A valid header, with the key derived from another credential, challenge or owner in the info."""
    owner = owner_nostr(seed)
    h = header(kind, owner, cred_id, cred_pub, challenge, nonce)
    key = wrap_key(secret, kind, info.get("cred_id", cred_id), info.get("cred_pub", cred_pub), info.get("challenge", challenge), info.get("owner", owner))
    return h + v.aes256gcm_encrypt(key, nonce, seed, h)


