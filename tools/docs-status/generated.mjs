// DOCS-COMPACT-A: the docs that are generated rather than written, besides the status blocks.
//
// - The version banner ("Applies to AgentLink X.Y.Z (pre-alpha, test networks)") between
//   `<!-- version-banner:start/end -->` in the public docs index, the guide and the technical
//   README only, from docs/status.yaml. Once a banner exists, a version stamp anywhere else in the
//   public docs is an error (one place to update per release instead of 68).
// - llms.txt, whole file, from the public docs index, the guide and technical SUMMARY files (titles,
//   ai-knowledge summaries, 4thTech Docs URLs) and the knowledge bundle link.
// Each generator is enforced only once its target carries its markers (or, for llms.txt, the
// generated notice), so the content can switch over page by page.

import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { BUNDLE_URL, DOCS, REPO_URL, WIKI_URL, detectLayout } from '../docs/paths.mjs';
import { orderedPages, pageUrls, parseMarker } from '../docs/pages.mjs';

// ---------- version banner ----------

export const BANNER_BLOCK = 'version-banner';
export const BANNER_FILES = [DOCS.publicReadme, DOCS.guideReadme, DOCS.technicalReadme];

/** "Applies to AgentLink 0.5.11 (pre-alpha, test networks)." */
export function renderBanner(data) {
  const version = String(data.version).replace(/^v/, '');
  const stage = data.stage ?? 'pre-alpha';
  const networks = data.networks ?? 'test';
  return `*Applies to AgentLink ${version} (${stage}, ${networks} networks).*`;
}

const STAMP_RE = /Applies to AgentLink \d/;

/** Removes generated banner blocks so what remains can be scanned for stray stamps. */
const withoutBanner = (text) =>
  text.replace(/<!-- version-banner:start -->[\s\S]*?<!-- version-banner:end -->/g, '');

/** Lines with a version stamp outside the banner: [`file:line: text`]. */
export function strayStamps(files) {
  const out = [];
  for (const [file, text] of files) {
    withoutBanner(text)
      .split('\n')
      .forEach((line, i) => {
        if (STAMP_RE.test(line)) out.push(`${file}:${i + 1}: ${line.trim().slice(0, 80)}`);
      });
  }
  return out;
}

// ---------- llms.txt ----------

export const LLMS_NOTICE =
  '<!-- Generated by tools/docs-status from the docs index, the SUMMARY files and docs/status.yaml. Do not edit: run node tools/docs-status/index.mjs -->';

/** The whole llms.txt. */
export function renderLlms(root, data) {
  const layout = detectLayout(root);
  const read = (rel) => readFileSync(join(root, rel), 'utf8');
  const urls = pageUrls(root, layout);
  const guideReadme = read(`${layout.guide}/README.md`);
  const about =
    parseMarker(guideReadme)?.summary ||
    /^\*\*([^*\n]+)\*\*\s*$/m.exec(guideReadme)?.[1] ||
    'AgentLink, by 4thTech: encrypted, provable exchange between AI agents.';
  const version = String(data.version).replace(/^v/, '');
  const out = [
    '# AgentLink',
    '',
    `> ${about} AgentLink is by 4thTech: client software plus an open protocol, OCC v2. Version ${version}, ${data.stage ?? 'pre-alpha'}, ${data.networks ?? 'test'} networks only.`,
    '',
    LLMS_NOTICE,
    '',
    `Everything in one file, for AI assistants: [AgentLink knowledge bundle](${BUNDLE_URL}). Read online: [4thTech Docs](${WIKI_URL}/products/agentlink).`,
  ];
  const sections = [
    ['User guide', layout.guide],
    ['Technical docs', layout.technical],
  ];
  const pages = orderedPages(root, layout);
  for (const [name, base] of sections) {
    out.push('', `## ${name}`, '');
    for (const { rel, title } of pages.filter((p) => p.rel.startsWith(`${base}/`))) {
      const marker = parseMarker(read(rel));
      if (marker?.mode === 'skip') continue;
      const url = urls.get(rel) ?? `${REPO_URL}/blob/main/${rel}`;
      out.push(`- [${title}](${url})${marker?.summary ? `: ${marker.summary}` : ''}`);
    }
  }
  out.push(
    '',
    '## Optional',
    '',
    `- [Project README](${REPO_URL}/blob/main/README.md): the public face of the project, with the current status`,
    `- [Specifications](${REPO_URL}/blob/main/${layout.specs}/00-README.md): the source of truth, including the security invariants`,
    `- [Decision log](${REPO_URL}/blob/main/${layout.specs}/decisions/README.md): every decision, one file each`,
    `- [Research](${REPO_URL}/blob/main/research/README.md): articles about agent-to-agent communication and AgentLink`,
    `- [Changelog](${REPO_URL}/blob/main/CHANGELOG.md): what changed in each release`,
    `- [Security policy](${REPO_URL}/blob/main/SECURITY.md): how to report a vulnerability privately`,
  );
  return `${out.join('\n')}\n`;
}
