/**
 * Generates the wiki copy of `srcRoot` into a scratch wiki and returns the problems GitBook would
 * show: a page missing from SUMMARY.md, a new technical section, or a link or image that does not
 * resolve in the copy. Nothing outside the scratch directory is written.
 */
export function preflight(srcRoot = REPO_ROOT) {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'wiki-preflight-'));
  try {
    fs.writeFileSync(path.join(tmp, 'SUMMARY.md'), SKELETON_SUMMARY);
    fs.writeFileSync(path.join(tmp, '.gitbook.yaml'), 'root: ./\n\nredirects:\n');
    try {
      sync({ tag: 'v0.0.0-preflight', srcRoot, commit: 'preflight', root: tmp });
    } catch (e) {
      return [e.message];
    }
    const problems = [];
    for (const f of walk(path.join(tmp, GUIDE_DEST))) {
      if (!f.endsWith('.md')) continue;
      const rel = relOf(tmp, f);
      for (const href of linkTargets(fs.readFileSync(f, 'utf8'))) {
        if (href.startsWith('#') || /^[a-z][a-z0-9+.-]*:/i.test(href) || href.startsWith('/'))
          continue;
        const target = decodeURI(href.split(/[#?]/)[0]);
        if (!target) continue;
        const resolved = posix.normalize(posix.join(posix.dirname(rel), target));
        if (!fs.existsSync(path.join(tmp, resolved)))
          problems.push(`${rel}: "${href}" does not resolve in the wiki copy`);
      }
    }
    return problems;
  } finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }
}

// ---------- CLI ----------

function parseArgs(argv) {
  const a = {};
  for (let i = 0; i < argv.length; i += 1) {
    const k = argv[i];
    if (['--check', '--preflight', '--recorded-tag', '--latest-tag'].includes(k))
      a[k.slice(2)] = true;
    else if (['--tag', '--source', '--wiki'].includes(k)) {
      const v = argv[i + 1];
      if (!v || v.startsWith('--')) throw new Error(`${k} needs a value`);
      a[k.slice(2)] = v;
      i += 1;
    } else throw new Error(`unknown argument ${k}`);
  }
  return a;
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  if (args.preflight) {
    const problems = preflight(args.source ? path.resolve(args.source) : REPO_ROOT);
    if (problems.length) {
      console.error(
        `wiki-sync --preflight: ${problems.length} problem(s)\n- ${problems.join('\n- ')}`,
      );
      process.exit(1);
    }
    console.log('wiki-sync --preflight: docs-site generates a clean 4thTech Docs copy.');
    return;
  }
  if (args['latest-tag']) {
    console.log(latestTag());
    return;
  }
  if (!args.wiki) throw new Error('--wiki <checkout of 4thtech/wiki.4thtech.io> is required');
  const root = path.resolve(args.wiki);
  if (!fs.existsSync(path.join(root, 'SUMMARY.md')))
    throw new Error(`${root} is not a checkout of the wiki (no SUMMARY.md)`);
  if (args['recorded-tag']) {
    console.log(readState(root)?.tag ?? 'none');
    return;
  }
  if (args.check) {
    const problems = checkState(root);
    if (problems.length) {
      console.error(`wiki-sync --check: ${problems.length} problem(s)\n- ${problems.join('\n- ')}`);
      process.exit(1);
    }
    const st = readState(root);
    console.log(`wiki-sync --check: OK (${st.files.length} files from ${st.tag})`);
    return;
  }
  const tag = args.tag ?? latestTag();
  if (!TAG_RE.test(tag))
    throw new Error(`"${tag}" is not a release tag like v0.4.15 (sync from release tags only)`);
  let srcRoot = args.source ? path.resolve(args.source) : null;
  let tmp = null;
  try {
    if (!srcRoot) {
      tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'agentlink-sync-'));
      srcRoot = path.join(tmp, 'agentlink');
      // Full history without file contents, so the tag can be checked against main.
      git(['clone', '--quiet', '--filter=blob:none', '--branch', tag, REPO_URL, srcRoot], tmp);
    }
    const commit = git(['rev-parse', 'HEAD'], srcRoot);
    // `git describe` picks one tag when several point at HEAD; accept the tag if it is any of them.
    const pointing = git(['tag', '--points-at', 'HEAD'], srcRoot)
      .split('\n')
      .map((t) => t.trim())
      .filter(Boolean);
    if (!pointing.includes(tag))
      throw new Error(
        `the source checkout is at ${pointing.join(', ') || 'no tag'}, not ${tag} (release tags only)`,
      );
    assertOnMain(srcRoot, commit);
    const r = sync({ tag, srcRoot, commit, root });
    console.log(
      `Synced AgentLink ${tag} (${commit.slice(0, 12)}): ${r.pages} pages, ${r.files} files.`,
    );
    console.log(`Added ${r.added.length}, removed ${r.removed.length}.`);
    for (const f of r.removed) console.log(`  - ${f}`);
  } finally {
    if (tmp) fs.rmSync(tmp, { recursive: true, force: true });
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    main();
  } catch (e) {
    console.error(`wiki-sync: ${e.message}`);
    process.exit(1);
  }
}
