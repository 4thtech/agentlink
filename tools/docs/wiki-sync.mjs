#!/usr/bin/env node
// DOCS-UNIFY: generates the AgentLink part of 4thTech Docs (wiki.4thtech.io) from docs-site/.
// One source: docs-site/ in this repo. The wiki repo 4thtech/wiki.4thtech.io holds a generated copy in
// `agentlink/`, its navigation entries in the root SUMMARY.md, AgentLink redirects in .gitbook.yaml and
// the record data/agentlink-sync.yaml. Everything else in the wiki (Welcome, news, deployments, the
// other 4thTech products) is written there by hand. Plain Node 22, no dependencies, no secrets.
//
//   node tools/docs/wiki-sync.mjs --preflight                         # CI here: the tree can be published
//   node tools/docs/wiki-sync.mjs --wiki <wiki checkout> --tag v0.4.15 [--source <checkout of that tag>]
//   node tools/docs/wiki-sync.mjs --wiki <wiki checkout> --check      # the wiki copy is unedited
//   node tools/docs/wiki-sync.mjs --wiki <wiki checkout> --recorded-tag   # prints the synced tag
//   node tools/docs/wiki-sync.mjs --latest-tag                        # prints the newest release tag
//
// Release tags only, never `main`, and the tag must be on main: the wiki shows what is released.
// Only .md pages and images are copied; symbolic links are refused; redirects stay inside agentlink/. docs-site/guide -> agentlink/,
// docs-site/technical -> agentlink/technical/, docs-site/assets -> agentlink/.gitbook/assets/.
// Ported from the wiki's scripts/sync-agentlink.mjs (same output byte for byte, same state file), so
// the wiki's own `--check` keeps working. Runbook: docs-site/MAINTAINING.md §2.

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

export const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
export const REPO_URL = 'https://github.com/4thtech/agentlink';
export const TAG_RE = /^v\d+\.\d+\.\d+(?:-[0-9A-Za-z.]+)?$/;
export const STATE_FILE = 'data/agentlink-sync.yaml';
const GUIDE_SRC = 'docs-site/guide';
const TECH_SRC = 'docs-site/technical';
const GUIDE_DEST = 'agentlink';
const TECH_DEST = 'agentlink/technical';
const ASSETS_SRC = 'docs-site/assets';
const ASSETS_DEST = 'agentlink/.gitbook/assets';
const IMAGE_RE = /\.(png|jpe?g|gif|svg|webp)$/i;
const SKIP_NAMES = new Set(['.gitbook.yaml', 'SUMMARY.md']);
const REDIRECT_START =
  '  # sync:agentlink:start (generated by scripts/sync-agentlink.mjs; do not edit)';
const REDIRECT_END = '  # sync:agentlink:end';

const posix = path.posix;
const sha256 = (buf) => crypto.createHash('sha256').update(buf).digest('hex');

// ---------- file mapping ----------

export function destFor(srcRel) {
  if (srcRel.startsWith(`${GUIDE_SRC}/`))
    return `${GUIDE_DEST}/${srcRel.slice(GUIDE_SRC.length + 1)}`;
  if (srcRel.startsWith(`${TECH_SRC}/`)) return `${TECH_DEST}/${srcRel.slice(TECH_SRC.length + 1)}`;
  if (srcRel.startsWith(`${ASSETS_SRC}/`))
    return `${ASSETS_DEST}/${srcRel.slice(ASSETS_SRC.length + 1)}`;
  return null;
}

// Symbolic links are refused everywhere (source and wiki): a link could pull a file from outside the
// tree into the public copy, or make a write land outside the wiki checkout.
export function assertNoLink(p) {
  let st;
  try {
    st = fs.lstatSync(p);
  } catch {
    return;
  }
  if (st.isSymbolicLink()) throw new Error(`${p} is a symbolic link: refused`);
}

function walk(dir) {
  assertNoLink(dir);
  const out = [];
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isSymbolicLink()) throw new Error(`${p} is a symbolic link: refused`);
    if (e.isDirectory()) {
      if (e.name !== '.git' && e.name !== 'node_modules') out.push(...walk(p));
    } else out.push(p);
  }
  return out;
}

const relOf = (root, f) => path.relative(root, f).split(path.sep).join('/');

/**
 * Only pages and images are published. Dotfiles and dot-folders are skipped, except `.gitbook/`
 * (GitBook's own image folder, which the guide uses).
 */
export function isPublishable(rel) {
  const parts = rel.split('/');
  if (parts.some((seg) => seg.startsWith('.') && seg !== '.gitbook')) return false;
  return /\.md$/i.test(rel) || IMAGE_RE.test(rel);
}

/** Source files (repo-relative, posix) that are copied. */
export function collectSources(srcRoot) {
  const out = [];
  for (const base of [GUIDE_SRC, TECH_SRC]) {
    const dir = path.join(srcRoot, base);
    if (!fs.existsSync(dir))
      throw new Error(
        `${base} does not exist (docs layout changed): update tools/docs/wiki-sync.mjs`,
      );
    for (const f of walk(dir)) {
      const rel = relOf(srcRoot, f);
      if (SKIP_NAMES.has(path.basename(rel)) || !isPublishable(rel)) continue;
      out.push(rel);
    }
  }
  const assets = path.join(srcRoot, ASSETS_SRC);
  if (fs.existsSync(assets)) {
    for (const f of walk(assets)) {
      const rel = relOf(srcRoot, f);
      if (IMAGE_RE.test(rel) && isPublishable(rel)) out.push(rel);
    }
  }
  return out.sort();
}

// ---------- link rewriting ----------

/** Replace fenced and inline code with placeholders so links inside code are left alone. */
function maskCode(text) {
  const saved = [];
  const keep = (m) => {
    saved.push(m);
    return `\uE000${saved.length - 1}\uE000`;
  };
  const masked = text.replace(/^(```|~~~)[\s\S]*?^\1[ \t]*$/gm, keep).replace(/`[^`\n]*`/g, keep);
  return { masked, restore: (s) => s.replace(/\uE000(\d+)\uE000/g, (_, i) => saved[Number(i)]) };
}

/**
 * ctx: { tag, srcRel, destRel, map: Map(srcRel -> destRel), kind(srcRel) -> 'file'|'dir'|null,
 * navMap: Map(url -> destRel) }
 */
export function rewriteHref(href, ctx) {
  if (href.startsWith('#') || /^(mailto:|tel:|data:)/.test(href)) return href;
  const pin = (type, repoPath, rest = '') => `${REPO_URL}/${type}/${ctx.tag}/${repoPath}${rest}`;
  const toWiki = (destTarget, rest) => {
    const rel = posix.relative(posix.dirname(ctx.destRel), destTarget);
    return (rel || posix.basename(destTarget)) + rest;
  };
  let m;
  if ((m = /^https:\/\/raw\.githubusercontent\.com\/4thtech\/agentlink\/main\/(.*)$/.exec(href))) {
    return `https://raw.githubusercontent.com/4thtech/agentlink/${ctx.tag}/${m[1]}`;
  }
  if ((m = /^https:\/\/wiki\.4thtech\.io\/?([^#?]*)(.*)$/.exec(href))) {
    const target = ctx.navMap.get(m[1].replace(/\/$/, ''));
    return target ? toWiki(target, m[2]) : href;
  }
  if (
    (m = /^https:\/\/github\.com\/4thtech\/agentlink\/(blob|tree)\/main\/?([^#?]*)([#?].*)?$/.exec(
      href,
    ))
  ) {
    const [, type, repoPath0, rest = ''] = m;
    const repoPath = repoPath0.replace(/\/$/, '');
    if (ctx.map.has(repoPath)) return toWiki(ctx.map.get(repoPath), rest);
    if (repoPath === GUIDE_SRC) return toWiki(`${GUIDE_DEST}/README.md`, rest);
    if (repoPath === TECH_SRC) return toWiki(`${TECH_DEST}/README.md`, rest);
    return pin(type, repoPath, rest);
  }
  if (/^[a-z][a-z0-9+.-]*:/i.test(href) || href.startsWith('/') || href.startsWith('//'))
    return href;
  // Relative link: resolve against the source file.
  const [pathPart, ...restParts] = href.split(/(?=[#?])/);
  const rest = restParts.join('');
  if (!pathPart) return href;
  const target = posix
    .normalize(posix.join(posix.dirname(ctx.srcRel), decodeURI(pathPart)))
    .replace(/\/$/, '');
  if (ctx.map.has(target)) return toWiki(ctx.map.get(target), rest);
  const kind = ctx.kind(target);
  if (kind) return pin(kind === 'dir' ? 'tree' : 'blob', target, rest);
  return href;
}

const LINK_PATTERNS = [
  /(!?\[[^\]]*\]\(\s*<?)([^)\s>]+)(>?(?:\s+"[^"]*")?\s*\))/g,
  /(\b(?:src|href)=")([^"]+)(")/g,
];
const REF_PATTERN = /^(\[[^\]]+\]:\s*)(\S+)/gm;

export function rewriteLinks(text, ctx) {
  const { masked, restore } = maskCode(text);
  let out = masked;
  for (const re of LINK_PATTERNS)
    out = out.replace(re, (_, a, h, b) => a + rewriteHref(h, ctx) + b);
  out = out.replace(REF_PATTERN, (_, a, h) => a + rewriteHref(h, ctx));
  // "Also on 4thTech Docs" lines point at the page that now contains them.
  out = out.replace(/^Also on 4thTech Docs:.*\n(\n)?/gm, '');
  return restore(out);
}

/** Every link target in a Markdown text, outside code. */
export function linkTargets(text) {
  const { masked } = maskCode(text);
  const out = [];
  for (const re of LINK_PATTERNS) for (const m of masked.matchAll(re)) out.push(m[2]);
  for (const m of masked.matchAll(REF_PATTERN)) out.push(m[2]);
  return out;
}

/** Adds the "synced" marker after any front matter. */
export function addHeader(text, tag) {
  const header = `<!-- Synced from 4thtech/agentlink docs-site@${tag}. Edit there, not here. -->`;
  const fm = /^---\n[\s\S]*?\n---\n/.exec(text);
  if (fm) return `${fm[0]}${header}\n${text.slice(fm[0].length)}`;
  return `${header}\n${text}`;
}

// ---------- SUMMARY ----------

/** Parses a docs-site SUMMARY.md into [{ depth, title, file, heading }]. */
export function parseSummary(text) {
  const out = [];
  let heading = '';
  for (const line of text.split('\n')) {
    const h = /^## (.+)$/.exec(line);
    if (h) {
      heading = h[1].trim();
      continue;
    }
    const m = /^(\s*)\* \[([^\]]*)\]\(([^)\s]+)\)/.exec(line);
    if (m)
      out.push({ depth: Math.floor(m[1].length / 2), title: m[2], file: decodeURI(m[3]), heading });
  }
  return out;
}

// Where each source section goes in the wiki navigation. `anchor` is the entry the block hangs from.
// The generator owns the CHILDREN of each anchor in the wiki's SUMMARY.md, never the anchor line:
// under `protocols/occ-v2.md` (a hand-written wiki page) every child entry is replaced by the
// technical Concepts pages on each sync, so do not add hand-written children there.
export const BLOCKS = [
  { id: 'guide', anchor: `${GUIDE_DEST}/README.md`, insertAfter: null, group: 'Products' },
  { id: 'concepts', anchor: 'protocols/occ-v2.md', insertAfter: null, group: 'Protocols' },
  {
    id: 'developers',
    anchor: `${TECH_DEST}/README.md`,
    insertAfter: 'developers/README.md',
    title: 'Build with AgentLink (OCC v2)',
    group: 'Developers',
  },
  {
    id: 'networks',
    anchor: `${TECH_DEST}/reference/networks-and-contracts.md`,
    insertAfter: 'occ-v1/reference/networks.md',
    title: 'AgentLink networks and contracts',
    group: 'Deployments',
  },
];

/** Splits the source entries into the navigation entries of each block (children only). */
export function planNavigation(guideEntries, techEntries) {
  const blocks = { guide: [], concepts: [], developers: [], networks: [] };
  const guideRoot = guideEntries[0];
  if (!guideRoot || guideRoot.file !== 'README.md')
    throw new Error('guide SUMMARY.md must start with README.md');
  for (const e of guideEntries.slice(1)) {
    blocks.guide.push({ depth: e.depth + 1, title: e.title, file: `${GUIDE_DEST}/${e.file}` });
  }
  const techRoot = techEntries[0];
  if (!techRoot || techRoot.file !== 'README.md')
    throw new Error('technical SUMMARY.md must start with README.md');
  const known = new Set(['Concepts', 'Guides', 'Reference', 'Project']);
  for (const e of techEntries.slice(1)) {
    if (!known.has(e.heading))
      throw new Error(
        `technical SUMMARY.md has a new section "${e.heading}": decide where it goes in BLOCKS`,
      );
    const file = `${TECH_DEST}/${e.file}`;
    if (file === BLOCKS[3].anchor) {
      blocks.networks.push({ depth: 0, title: BLOCKS[3].title, file });
      continue;
    }
    if (e.heading === 'Concepts')
      blocks.concepts.push({ depth: e.depth + 1, title: e.title, file });
    else blocks.developers.push({ depth: e.depth + 1, title: e.title, file });
  }
  return blocks;
}

const indentOf = (line) => /^(\s*)/.exec(line)[1].length;
const lineLink = (line) => /^\s*\* \[[^\]]*\]\(([^)\s]+)\)/.exec(line)?.[1];

function subtreeEnd(lines, i) {
  const base = indentOf(lines[i]);
  let j = i + 1;
  while (j < lines.length && /^\s*\* /.test(lines[j]) && indentOf(lines[j]) > base) j += 1;
  return j;
}

const fmt = (e, extraDepth = 0) => `${'  '.repeat(e.depth + extraDepth)}* [${e.title}](${e.file})`;

/** Rewrites the root SUMMARY.md text. Throws when an anchor is missing. */
export function updateSummary(summary, nav) {
  const lines = summary.split('\n');
  const find = (file) => lines.findIndex((l) => lineLink(l) === file);
  for (const b of BLOCKS) {
    const children = nav[b.id];
    const at = find(b.anchor);
    if (b.id === 'networks') {
      const entry = children[0];
      if (at !== -1) lines.splice(at, subtreeEnd(lines, at) - at, fmt(entry));
      else {
        const after = find(b.insertAfter);
        if (after === -1) throw new Error(`SUMMARY.md has no entry for ${b.insertAfter}`);
        lines.splice(subtreeEnd(lines, after), 0, fmt(entry));
      }
      continue;
    }
    if (at !== -1) {
      const rootLine = lines[at];
      lines.splice(at, subtreeEnd(lines, at) - at, rootLine, ...children.map((e) => fmt(e)));
    } else {
      const after = b.insertAfter ? find(b.insertAfter) : -1;
      if (after === -1) throw new Error(`SUMMARY.md has no entry for ${b.insertAfter ?? b.anchor}`);
      const root = `* [${b.title}](${b.anchor})`;
      lines.splice(subtreeEnd(lines, after), 0, root, ...children.map((e) => fmt(e)));
    }
  }
  return lines.join('\n');
}

// ---------- live URLs (GitBook: group slug + parent slugs + own slug) ----------

export function slugify(s) {
  return s
    .toLowerCase()
    .replace(/&/g, ' and ')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

function pageSlug(file) {
  const p = file.replace(/\.md$/, '').split('/');
  if (p[p.length - 1].toLowerCase() === 'readme') p.pop();
  return p.length ? p[p.length - 1] : '';
}

/** Returns [{ file, url }] in SUMMARY order. */
export function navUrls(summary) {
  const out = [];
  let group = '';
  const stack = [];
  const used = new Map();
  for (const line of summary.split('\n')) {
    const g = /^## (.+)$/.exec(line);
    if (g) {
      group = slugify(g[1].trim());
      stack.length = 0;
      used.clear();
      continue;
    }
    const m = /^(\s*)\* \[[^\]]*\]\(([^)\s]+)\)/.exec(line);
    if (!m) continue;
    const depth = Math.floor(m[1].length / 2);
    const file = decodeURI(m[2]);
    stack.length = depth;
    let slug = pageSlug(file);
    // Siblings with the same slug get -1, -2, ... (the first keeps the plain slug).
    const scope = [group, ...stack].join('/') + '|' + slug;
    const n = used.get(scope) ?? 0;
    used.set(scope, n + 1);
    if (n > 0) slug = `${slug}-${n}`;
    stack.push(slug);
    out.push({
      file,
      url: file === 'README.md' ? '' : [group, ...stack].filter(Boolean).join('/'),
    });
  }
  return out;
}

// ---------- redirects ----------

/** Reads the `redirects:` of a docs-site .gitbook.yaml; returns [[from, to]] (empty when none). */
export function readRedirects(yamlText) {
  const out = [];
  let inRedirects = false;
  for (const line of yamlText.split('\n')) {
    if (/^\S/.test(line)) inRedirects = line.startsWith('redirects:');
    const m = inRedirects && /^\s+([^#:\s][^:]*):\s*(\S+)\s*$/.exec(line);
    if (m) out.push([m[1], m[2]]);
  }
  return out;
}

/** A redirect may only map an agentlink/ URL to a file under ./agentlink/ (no `..`, no other section). */
export function assertAgentlinkRedirect(from, to) {
  const okFrom = /^agentlink\/[A-Za-z0-9._/-]+$/.test(from) && !from.split('/').includes('..');
  const norm = posix.normalize(to);
  const okTo = /^\.\/agentlink\/[A-Za-z0-9._/-]+\.md$/.test(to) && norm.startsWith('agentlink/');
  if (!okFrom || !okTo) throw new Error(`redirect ${from} -> ${to} leaves agentlink/: refused`);
}

export function updateRedirects(gitbookYaml, redirects) {
  const a = gitbookYaml.indexOf(REDIRECT_START);
  const b = gitbookYaml.indexOf(REDIRECT_END);
  let base = gitbookYaml;
  if (a !== -1 && b !== -1)
    base =
      gitbookYaml.slice(0, a).replace(/\n+$/, '\n') +
      gitbookYaml.slice(b + REDIRECT_END.length).replace(/^\n/, '');
  if (!redirects.length) return base;
  for (const [from, to] of redirects) assertAgentlinkRedirect(from, to);
  const block = [
    REDIRECT_START,
    ...redirects.map(([from, to]) => `  ${from}: ${to}`),
    REDIRECT_END,
  ].join('\n');
  // The redirects section is last in the file; append inside it.
  return `${base.replace(/\n*$/, '\n')}${block}\n`;
}

// ---------- state file (same format as the wiki's scripts/sync-agentlink.mjs) ----------

export function renderState(tag, commit, files) {
  const lines = [
    '# Written by scripts/sync-agentlink.mjs. Do not edit by hand.',
    '# `node scripts/sync-agentlink.mjs --check` fails when a synced file differs from its recorded hash.',
    `tag: ${tag}`,
    `commit: ${commit}`,
    'files:',
  ];
  for (const [p, h] of [...files].sort(([a], [b]) => (a < b ? -1 : 1)))
    lines.push(`  - path: ${p}`, `    sha256: ${h}`);
  return lines.join('\n') + '\n';
}

/** Parses the state file written by renderState. */
export function parseState(text) {
  const st = { tag: null, commit: null, files: [] };
  for (const line of text.split('\n')) {
    let m;
    if ((m = /^tag:\s*(\S+)/.exec(line))) st.tag = m[1];
    else if ((m = /^commit:\s*(\S+)/.exec(line))) st.commit = m[1];
    else if ((m = /^\s+- path:\s*(\S+)/.exec(line))) st.files.push({ path: m[1], sha256: null });
    else if ((m = /^\s+sha256:\s*([0-9a-f]{64})/.exec(line)) && st.files.length)
      st.files[st.files.length - 1].sha256 = m[1];
  }
  return st;
}

export function readState(root) {
  const p = path.join(root, STATE_FILE);
  assertNoLink(path.join(root, 'data'));
  assertNoLink(p);
  if (!fs.existsSync(p)) return null;
  return parseState(fs.readFileSync(p, 'utf8'));
}

/** Returns a list of problems: hand edits, missing or extra files under agentlink/. */
export function checkState(root) {
  const st = readState(root);
  if (!st) return [`${STATE_FILE} is missing: run tools/docs/wiki-sync.mjs`];
  const problems = [];
  const listed = new Set();
  for (const f of st.files) {
    listed.add(f.path);
    const p = path.join(root, f.path);
    if (!fs.existsSync(p)) problems.push(`${f.path}: synced file is missing`);
    else if (sha256(fs.readFileSync(p)) !== f.sha256)
      problems.push(
        `${f.path}: edited by hand (synced from ${st.tag}); edit docs-site in 4thtech/agentlink and sync again`,
      );
  }
  const dir = path.join(root, GUIDE_DEST);
  if (fs.existsSync(dir)) {
    for (const f of walk(dir)) {
      const rel = relOf(root, f);
      if (!listed.has(rel))
        problems.push(
          `${rel}: not part of the sync; agentlink/ is generated, add it to 4thtech/agentlink docs-site instead`,
        );
    }
  }
  return problems;
}

// ---------- sync ----------

function git(args, cwd) {
  return execFileSync('git', args, {
    cwd,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  }).trim();
}

export function compareTags(x, y) {
  const key = (t) => t.slice(1).split(/[.-]/).slice(0, 3).map(Number);
  const a = key(x);
  const b = key(y);
  for (let i = 0; i < 3; i += 1) if (a[i] !== b[i]) return a[i] - b[i];
  return 0;
}

/** Throws unless `commit` is on main (`mainRef`, default origin/main) of the source checkout. */
export function assertOnMain(srcRoot, commit, mainRef = 'origin/main') {
  try {
    git(['rev-parse', '--verify', '--quiet', `${mainRef}^{commit}`], srcRoot);
  } catch {
    throw new Error(`the source checkout has no ${mainRef}: cannot check the tag is on main`);
  }
  try {
    git(['merge-base', '--is-ancestor', commit, mainRef], srcRoot);
  } catch {
    throw new Error(`${commit.slice(0, 12)} is not on ${mainRef}: release tags from main only`);
  }
}

export function latestTag(cwd = REPO_ROOT) {
  const out = git(['ls-remote', '--tags', '--refs', REPO_URL, 'v*'], cwd);
  const tags = out
    .split('\n')
    .map((l) => l.split('refs/tags/')[1])
    .filter((t) => t && TAG_RE.test(t) && !t.includes('-'));
  if (!tags.length) throw new Error('no release tags found');
  return tags.sort(compareTags)[tags.length - 1];
}

export function sync({ tag, srcRoot, commit, root }) {
  for (const rel of ['SUMMARY.md', '.gitbook.yaml', 'data', STATE_FILE, GUIDE_DEST])
    assertNoLink(path.join(root, rel));
  const sources = collectSources(srcRoot);
  const map = new Map(sources.map((s) => [s, destFor(s)]));
  const kind = (rel) => {
    const p = path.join(srcRoot, rel);
    if (!fs.existsSync(p)) return null;
    return fs.statSync(p).isDirectory() ? 'dir' : 'file';
  };

  // Navigation first (it also tells us which pages exist).
  const guideEntries = parseSummary(
    fs.readFileSync(path.join(srcRoot, GUIDE_SRC, 'SUMMARY.md'), 'utf8'),
  );
  const techEntries = parseSummary(
    fs.readFileSync(path.join(srcRoot, TECH_SRC, 'SUMMARY.md'), 'utf8'),
  );
  const nav = planNavigation(guideEntries, techEntries);
  const listedDest = new Set([
    `${GUIDE_DEST}/README.md`,
    `${TECH_DEST}/README.md`,
    ...[...nav.guide, ...nav.concepts, ...nav.developers, ...nav.networks].map((e) => e.file),
  ]);
  const mdDest = [...map.values()].filter((d) => d.endsWith('.md'));
  const unlisted = mdDest.filter((d) => !listedDest.has(d));
  if (unlisted.length)
    throw new Error(`pages in the source but not in its SUMMARY.md: ${unlisted.join(', ')}`);
  const missing = [...listedDest].filter((d) => !mdDest.includes(d));
  if (missing.length)
    throw new Error(`SUMMARY.md lists files that are not in the source: ${missing.join(', ')}`);

  // Live URL -> file for links back to the wiki itself.
  const summaryPath = path.join(root, 'SUMMARY.md');
  const newSummary = updateSummary(fs.readFileSync(summaryPath, 'utf8'), nav);
  const navMap = new Map();
  for (const n of navUrls(newSummary)) navMap.set(n.url, n.file);

  // Replace the whole agentlink/ folder.
  const before = readState(root)?.files.map((f) => f.path) ?? [];
  const agentDir = path.join(root, GUIDE_DEST);
  const oldFiles = fs.existsSync(agentDir) ? walk(agentDir).map((f) => relOf(root, f)) : [];
  fs.rmSync(agentDir, { recursive: true, force: true });

  const written = new Map();
  for (const srcRel of sources) {
    const destRel = map.get(srcRel);
    const out = path.join(root, destRel);
    fs.mkdirSync(path.dirname(out), { recursive: true });
    const buf = fs.readFileSync(path.join(srcRoot, srcRel));
    let data = buf;
    if (srcRel.endsWith('.md')) {
      const ctx = { tag, srcRel, destRel, map, kind, navMap };
      data = Buffer.from(addHeader(rewriteLinks(buf.toString('utf8'), ctx), tag));
    }
    fs.writeFileSync(out, data);
    written.set(destRel, sha256(data));
  }

  fs.writeFileSync(summaryPath, newSummary);

  // Redirects from the source sections, with the section prefix.
  const redirects = [];
  for (const [base, destBase] of [
    [GUIDE_SRC, GUIDE_DEST],
    [TECH_SRC, TECH_DEST],
  ]) {
    const y = path.join(srcRoot, base, '.gitbook.yaml');
    if (!fs.existsSync(y)) continue;
    for (const [from, to] of readRedirects(fs.readFileSync(y, 'utf8'))) {
      redirects.push([
        `${destBase}/${from}`,
        `./${posix.normalize(posix.join(destBase, to.replace(/^\.\//, '')))}`,
      ]);
    }
  }
  const gbPath = path.join(root, '.gitbook.yaml');
  fs.writeFileSync(gbPath, updateRedirects(fs.readFileSync(gbPath, 'utf8'), redirects));

  fs.mkdirSync(path.join(root, 'data'), { recursive: true });
  fs.writeFileSync(path.join(root, STATE_FILE), renderState(tag, commit, written));

  const now = new Set(written.keys());
  const was = new Set(oldFiles.length ? oldFiles : before);
  return {
    added: [...now].filter((f) => !was.has(f)).sort(),
    removed: [...was].filter((f) => !now.has(f)).sort(),
    pages: [...now].filter((f) => f.endsWith('.md')).length,
    files: now.size,
  };
}

