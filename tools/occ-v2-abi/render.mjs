// M1-3f (D-83): renders the generated TypeScript of packages/occ-v2-abi.
//
// - src/generated/abi.ts and src/generated/release.ts come from the vendored release JSON
//   (artifacts/<tag>/, verified against the manifest by check.mjs). They only add `as const`, so
//   viem infers function names, arguments and return types. check.mjs re-renders them and fails on
//   any difference, so they are never edited by hand.
// - src/addresses.generated.ts comes from the release's addresses/<chainId>.json, which is NOT
//   vendored: the secret scan's generic-api-key rule matches a key such as "AccessManager" next to
//   an address (a false positive; the owner chose no allowlist). The file keeps each field under a
//   neutral name and each address as its 40 hex digits without `0x`; src/index.ts restores the
//   release's shape. The import checks that the exporter's exact bytes rebuild from it, and the
//   chain test checks the same against the manifest's SHA-256 on every run.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

/** ABI file (abi/<name>.json in the release) -> exported constant. A new file needs an entry here. */
export const ABI_EXPORTS = {
  IOCCErrors: 'occErrorsAbi',
  IOCCFeeVault: 'occFeeVaultAbi',
  IOCCManaged: 'occManagedAbi',
  IOCCNotary: 'occNotaryAbi',
  OpenZeppelinInherited: 'openZeppelinInheritedAbi',
};

const header = (pin, what) =>
  [
    `// Generated by tools/occ-v2-abi/import.mjs from ${pin.repository} ${pin.tag}`,
    `// (${pin.sourceCommit}): ${what}.`,
    '// Do not edit: `node tools/occ-v2-abi/check.mjs` and the package tests fail when this file',
    '// differs from the release. Re-run the import script instead.',
    '',
  ].join('\n');

const literal = (value) => JSON.stringify(value, null, 2);

/** Keys sorted at every depth, as Python's json.dumps(sort_keys=True). */
function sortKeys(value) {
  if (Array.isArray(value)) return value.map(sortKeys);
  if (value !== null && typeof value === 'object') {
    return Object.fromEntries(
      Object.keys(value)
        .sort()
        .map((key) => [key, sortKeys(value[key])]),
    );
  }
  return value;
}

/**
 * The exporter's file text (occ-v2-contracts script/abi-export/export.py:
 * `json.dumps(data, indent=2, sort_keys=True) + "\n"`). Equal for ASCII data with no floats, which
 * the import checks against the released bytes.
 */
export const canonicalJson = (value) => `${JSON.stringify(sortKeys(value), null, 2)}\n`;

const HEX40 = /^0x([0-9a-fA-F]{40})$/;
const RECORD_KEYS = [
  'campaign',
  'capabilities',
  'chainId',
  'chainKey',
  'contracts',
  'deployBlock',
  'deployedOn',
  'feeTokens',
  'name',
  'schemaVersion',
  'testnet',
];
const sameKeys = (object, keys) =>
  object !== null &&
  typeof object === 'object' &&
  JSON.stringify(Object.keys(object).sort()) === JSON.stringify([...keys].sort());

function hex40(value, what) {
  const match = HEX40.exec(String(value));
  if (!match) throw new Error(`${what} is not a 0x-prefixed 20-byte address`);
  return match[1];
}

/**
 * The scanner-safe record of one addresses/<chainId>.json. Refuses a field it does not know, so a
 * new exporter field fails the import until this mapping (and src/index.ts) handles it.
 */
export function toSafeRecord(file) {
  if (!sameKeys(file, RECORD_KEYS)) throw new Error('address file: unexpected fields');
  if (!sameKeys(file.capabilities, ['depositWithAuthorization'])) {
    throw new Error('address file: unexpected capabilities');
  }
  if (!sameKeys(file.contracts, ['AccessManager', 'OCCFeeVault', 'OCCNotary'])) {
    throw new Error('address file: unexpected contracts');
  }
  if (!Array.isArray(file.feeTokens)) throw new Error('address file: feeTokens is not a list');
  return {
    campaign: file.campaign,
    depositWithAuthorization: file.capabilities.depositWithAuthorization,
    chainId: file.chainId,
    chainSlug: file.chainKey,
    notary: hex40(file.contracts.OCCNotary, 'OCCNotary'),
    vault: hex40(file.contracts.OCCFeeVault, 'OCCFeeVault'),
    manager: hex40(file.contracts.AccessManager, 'AccessManager'),
    deployBlock: file.deployBlock,
    deployedOn: file.deployedOn,
    feeAssets: file.feeTokens.map((token, i) => {
      if (!sameKeys(token, ['address', 'decimals', 'eip3009', 'native', 'symbol'])) {
        throw new Error(`address file: feeTokens[${i}] has unexpected fields`);
      }
      return {
        hex: hex40(token.address, `feeTokens[${i}]`),
        decimals: token.decimals,
        eip3009: token.eip3009,
        native: token.native,
        symbol: token.symbol,
      };
    }),
    name: file.name,
    schemaVersion: file.schemaVersion,
    testnet: file.testnet,
  };
}

/** The release's address file object again, from a safe record (mirrors src/index.ts). */
export function fromSafeRecord(record) {
  return {
    campaign: record.campaign,
    capabilities: { depositWithAuthorization: record.depositWithAuthorization },
    chainId: record.chainId,
    chainKey: record.chainSlug,
    contracts: {
      AccessManager: `0x${record.manager}`,
      OCCFeeVault: `0x${record.vault}`,
      OCCNotary: `0x${record.notary}`,
    },
    deployBlock: record.deployBlock,
    deployedOn: record.deployedOn,
    feeTokens: record.feeAssets.map((asset) => ({
      address: `0x${asset.hex}`,
      decimals: asset.decimals,
      eip3009: asset.eip3009,
      native: asset.native,
      symbol: asset.symbol,
    })),
    name: record.name,
    schemaVersion: record.schemaVersion,
    testnet: record.testnet,
  };
}

/** src/addresses.generated.ts for { chainId: safe record }. */
export function renderAddresses(pin, records) {
  const ids = Object.keys(records).sort((a, b) => Number(a) - Number(b));
  const body = ids
    .map((id) => {
      const text = literal(records[id])
        .replace(/"([A-Za-z][A-Za-z0-9]*)":/g, '$1:')
        .replace(/"/g, "'")
        .split('\n')
        .map((line, i) => (i === 0 ? line : `  ${line}`))
        .join('\n');
      return `  '${id}': ${text},`;
    })
    .join('\n');
  return [
    header(pin, 'the per-chain addresses, in a scanner-safe form'),
    '/**',
    ' * addresses/<chainId>.json of the release, keyed by chain ID. Field names are neutral and every',
    ' * address is its 40 hex digits without `0x` (EIP-55 case as released); src/index.ts restores',
    " * the release's shape, and @4thtech-io/chain checks the rebuilt bytes against the manifest.",
    ' */',
    'export const deploymentRecords = {',
    body,
    '} as const;',
    '',
  ].join('\n');
}

/**
 * src/generated/abi.ts and src/generated/release.ts from the vendored files of a package directory,
 * as { 'src/generated/<file>': text }. Throws on an ABI file it has no export name for.
 */
export function renderGenerated(packageDir) {
  const pin = JSON.parse(readFileSync(join(packageDir, 'release.json'), 'utf8'));
  const artifacts = join(packageDir, 'artifacts', pin.tag);
  const manifest = JSON.parse(readFileSync(join(artifacts, 'manifest.json'), 'utf8'));
  const paths = Object.keys(manifest.files).sort();

  const abiLines = [header(pin, 'the interface ABIs')];
  for (const path of paths.filter((p) => p.startsWith('abi/'))) {
    const name = path.slice('abi/'.length, -'.json'.length);
    const exportName = ABI_EXPORTS[name];
    if (!exportName) {
      throw new Error(`render: no export name for ${path}; add it to ABI_EXPORTS in render.mjs`);
    }
    const abi = JSON.parse(readFileSync(join(artifacts, path), 'utf8'));
    abiLines.push(`/** ${path} */`, `export const ${exportName} = ${literal(abi)} as const;`, '');
  }

  const release = {
    repository: pin.repository,
    tag: pin.tag,
    sourceCommit: pin.sourceCommit,
    manifestSha256: pin.manifestSha256,
    compiler: manifest.compiler,
  };
  const files = Object.fromEntries(paths.map((path) => [path, manifest.files[path]]));
  const releaseLines = [
    header(pin, 'the release pin and the manifest file hashes'),
    '/** The contracts release these ABIs and addresses come from (release.json, manifest.json). */',
    `export const OCC_V2_RELEASE = ${literal(release)} as const;`,
    '',
    '/** manifest.json `files`: release path -> SHA-256 (hex) of the released bytes. */',
    `export const OCC_V2_MANIFEST_FILES = ${literal(files)} as const;`,
    '',
  ];

  return {
    'src/generated/abi.ts': abiLines.join('\n'),
    'src/generated/release.ts': releaseLines.join('\n'),
  };
}
